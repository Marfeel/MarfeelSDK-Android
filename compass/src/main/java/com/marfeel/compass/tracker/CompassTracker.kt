internal const val compassNotInitializedErrorMessage =
    "Compass not initialized. Make sure CompassTracking::initialize has been called"

internal const val bannedPageTechnologyValue =
    "Page technology value should be greater than 100"

/**
 * CompassTracking is the entry point for all interactions with the library.
 * To access to CompassTracking just retrieve its singleton instance by calling [CompassTracking.getInstance].
 *
 */
interface CompassTracking {
    /**
     * @see trackNewPage(String)
     */
    @Deprecated("Use trackNewPage(url) method", replaceWith = ReplaceWith("trackNewPage(url)"))
    fun startPageView(url: String)

    /**
     * @see trackNewPage(String, ScrollView)
     */
    @Deprecated("Use trackNewPage(url, scrollView) method", replaceWith = ReplaceWith("trackNewPage(url, scrollView)"))
    fun startPageView(url: String, scrollView: ScrollView)

    /**
     * @see trackNewPage(String, ScrollView)
     */
    @Deprecated("Use trackNewPage(url, scrollView) method", replaceWith = ReplaceWith("trackNewPage(url, scrollView)"))
    fun startPageView(url: String, scrollView: RecyclerView)

    /**
     * @see trackNewPage(String, ScrollView)
     */
    @Deprecated("Use trackNewPage(url, scrollView) method", replaceWith = ReplaceWith("trackNewPage(url, scrollView)"))
    fun<T> startPageView(url: String, scrollView: T) where T: FrameLayout, T: ScrollingView


    /**
     * Starts to track the time a user remains on the page given by the [url] parameter as well as the scroll percentage of the content.
     *
     * @param url the url of the page being tracked.
     * @param scrollView view showing the url content.
     * @param rs recirculation source
     */
    fun trackNewPage(url: String, scrollView: ScrollView, rs: String? = null)

    /**
     * @see trackNewPage(String, ScrollView)
     */
    fun trackNewPage(url: String, scrollView: RecyclerView, rs: String? = null)

    /**
     * @see trackNewPage(String, ScrollView)
     */
    fun<T> trackNewPage(url: String, scrollView: T, rs: String? = null) where T: FrameLayout, T: ScrollingView

    /**
     * Starts to track the time a user remains on a page given by the [url] parameter.
     *
     * @param url the url of the page being tracked.
     * @param rs recirculation source
     */
    fun trackNewPage(url: String, rs: String? = null)

    /**
     * Starts to track the time a user remains on the page given by the [screen] parameter as well as the scroll percentage of the content.
     *
     * @param screen the name of the screen being tracked.
     * @param scrollView view showing the screen content.
     * @param rs recirculation source
     */
    fun trackScreen(screen: String, scrollView: ScrollView, rs: String? = null)

    /**
     * @see trackScreen(String, ScrollView)
     */
    fun trackScreen(screen: String, scrollView: RecyclerView, rs: String? = null)

    /**
     * @see trackScreen(String, ScrollView)
     */
    fun<T> trackScreen(screen: String, scrollView: T, rs: String? = null) where T: FrameLayout, T: ScrollingView

    /**
     * Starts to track the time a user remains on a page given by the [screen] parameter.
     *
     * @param screen the name of the screen being tracked.
     */
    fun trackScreen(screen: String, rs: String? = null)

    /**
     * Stops the tracking.
     */
    fun stopTracking()

    /**
     * Associates the user of the application with the records generated by Compass.
     * @param userId the user's identifier in your platform
     */
    @Deprecated("Use setSiteUserId(userID) method", replaceWith = ReplaceWith("setSiteUserId(userId)"))
    fun setUserId(userId: String)

    /**
     * Gets the internal userId used by marfeel for representing uniquely the user
     */
    fun getUserId(): String

    /**
     * Gets the internal sessionId used by marfeel for representing uniquely the current session
     */
    fun getSessionId(): String

    /**
     * Associates the user of the application with the records generated by Compass.
     * @param userId the user's identifier in your platform
     */
    fun setSiteUserId(userId: String)

    /**
     * Sets the user type.
     * @param userType The user type.
     */
    fun setUserType(userType: UserType)

    /**
     * Gets the RFV code from Compass.
     *
     * This function should not be called from the main thread, **if it is called from the main thread, an exception is thrown**.
     */
    fun getRFV(): String?

    /**
     * Gets the RFV code from Compass asynchronously.
     *
     * @param onResult the callback function to handle te result.
     */
    fun getRFV(onResult: (String?) -> Unit)

    fun trackConversion(conversion: String)

    fun trackConversion(conversion: String, options: ConversionOptions)

    /**
     * Sets variables for the current page view.
     *
     * @param name variable name
     * @param value variable value
     */
    fun setPageVar(name: String, value: String)

    /**
     * Sets metrics for the current page view.
     *
     * @param name variable name
     * @param value variable value
     */
    fun setPageMetric(name: String, value: Int)

    /**
     * Sets variables for the current session.
     *
     * @param name variable name
     * @param value variable value
     */
    fun setSessionVar(name: String, value: String)

    /**
     * Sets persistent variables for the user.
     *
     * @param name variable name
     * @param value variable value
     */
    fun setUserVar(name: String, value: String)

    /**
     * Adds persistent user segment for the user.
     *
     * @param name user segment name
     */
    fun addUserSegment(name: String)

    /**
     * Sets persistent user segments for the user, overriding previous ones.
     *
     * @param segments user segments names
     */
    fun setUserSegments(segments: List<String>)

    /**
     * removes user segment for the user.
     *
     * @param name user segment name
     */
    fun removeUserSegment(name: String)

    /**
     * Clears all user segments for the user.
     */
    fun clearUserSegments()

    /**
     * The user segments as a beacon sends them (`useg`): the device-owned segments
     * unioned with the Server Segments the CDP asserts, server first, deduplicated and
     * capped at 100. When the union overflows the user var `mrf_tooManySegments` is set
     * and device-owned segments are the ones dropped. Storage itself is never trimmed.
     *
     * Reads whatever Server Segments are known right now; see [getUserSegmentsAsync] to
     * resolve identity first.
     */
    fun getUserSegments(): List<String>

    /**
     * @see getUserSegments — resolves identity first so the Server Segments are current.
     */
    suspend fun getUserSegmentsAsync(): List<String>

    /**
     * The user vars as a beacon sends them (`uvar`): the device-owned vars followed by
     * the Server Properties the CDP computed for this user. Device-owned wins on a key
     * collision. Reads whatever Server Properties are known right now.
     */
    fun getUserVars(): Map<String, String>

    /**
     * @see getUserVars — resolves identity first so the Server Properties are current.
     */
    suspend fun getUserVarsAsync(): Map<String, String>

    /**
     * Turns this device into a **new visitor**. Call it on sign-out.
     *
     * Synchronously — before this function first suspends — the registered user id is
     * dropped, a new internal user id, first visit and session are minted, user vars and
     * segments are emptied, the cached RFV is dropped and the whole local CDP state
     * (master_id, cached rfv/cohorts, mirrors, meters, anonymous consent memory) is wiped.
     * The remaining suspension is a best-effort remote CDP reset bounded to five seconds.
     *
     * It never throws and never re-resolves identity: the next [trackNewPage] does. The
     * current page keeps its page id, so a sign-out that stays on screen should be
     * followed by a new [trackNewPage] / [trackScreen]. Concurrent calls share one run.
     */
    suspend fun resetUser()

    /**
     * @see resetUser — callback form. The local rotation still happens synchronously
     * before this returns; [onComplete] fires once the remote tail settles.
     */
    fun resetUser(onComplete: () -> Unit)

    @Deprecated("Use resetUser()", ReplaceWith("resetUser()"))
    suspend fun resetIdentity()

    /**
     * Sets user consent value.
     * @param hasConsent user consent
     */
    fun setUserConsent(hasConsent: Boolean)

    /**
     * Defines landing page por the whole session.
     *
     * @param landingPage landingPage url or screen name.
     */
    fun setLandingPage(landingPage: String)

    /**
     * Manually updates the scroll percentage for the current page.
     *
     * Use this when the scroll view is not a native Android view (e.g. Flutter, Compose).
     * The value is only updated if it exceeds the previously recorded maximum.
     *
     * @param scrollPosition scroll percentage (0-100).
     */
    fun updateScrollPercentage(scrollPosition: Int)

    companion object {
        /**
         * Prepare the Compass SDK to track the pages.
         *
         * Typically, you should initialize the Compass SDK from your Application class.
         * @param context The Android Context.
         * @param accountId Compass account id.
         * @param tech PageTechnology. Only values greater than 100 or 4 or 11, which represents android, are accepted.
         * @param enableCdp opt-in to the CDP subsystem. When false (default) the whole subsystem is inert
         */
        fun initialize(
            context: Context,
            accountId: String,
            tech: Int = androidPageType,
            enableCdp: Boolean = false
        ) {
            require(tech > 100 || androidCorePageTypes.contains(tech)) { bannedPageTechnologyValue }

            CompassComponent.context = context.applicationContext
            if (!CompassTracker.initialized) {
                CompassTracker.initialize(accountId, tech, enableCdp)
            }
        }

        /**
         *
         * @return The singleton instance of the CompassTracking interface
         */
        fun getInstance(): CompassTracking = CompassTracker

        /**
         *
         * @return If compass instance has been initialized properly or not
         */
        internal val initialized: Boolean
            get() = CompassTracker.initialized
    }
}

internal object CompassTracker : CompassTracking {

    private val pingEmitter: IngestPingEmitter by lazy { CompassComponent.ingestPingEmitter }
    private val storage: Storage by lazy { CompassComponent.storage }
    private val sessionStorage: SessionStorage by lazy { CompassComponent.sessionStorage }
    private val getRFV: GetRFV by lazy { CompassComponent.getRFV() }
    private val coroutineScope = CoroutineScope(SupervisorJob() + Dispatchers.IO)

    /**
     * The merged, trimmed read-side views the beacon sends as `useg` / `uvar`; keeps
     * `mrf_tooManySegments` in step with the segment union on every read.
     */
    private val userData: UserDataMerger by lazy {
        UserDataMerger(
            cdpEnabled = { sessionStorage.readCdpEnabled() },
            readOwnedSegments = { storage.readUserSegments() },
            readOwnedVars = { storage.readUserVars() },
            listServerSegments = CdpTracker::listServerSegments,
            getServerSegments = { CdpTracker.getServerSegments() },
            listServerProperties = CdpTracker::listServerProperties,
            getServerProperties = { CdpTracker.getServerProperties() },
            trimmer = SegmentTrimmer(
                readOwnedUserVars = { storage.readUserVars() },
                setUserVar = { name, value -> writeUserVar(name, value) },
                removeUserVar = { name -> writeUserVar(name, null) }
            )
        )
    }

    private val userResetter: UserResetter by lazy {
        val rotation = UserRotation(
            storage = storage,
            sessionStorage = sessionStorage,
            updateEmitterSession = pingEmitter::updateSessionId,
            clearRfvCache = getRFV::clearCache,
            clearCdpIdentity = CdpTracker::clearIdentity
        )
        UserResetter(
            rotateLocalUser = rotation::rotate,
            clearRemoteState = { CdpTracker.resetRemoteIdentity() }
        )
    }


    internal val initialized: Boolean
        get() = sessionStorage.readAccountId() != null

    internal fun initialize(accountId: String, tech: Int, enableCdp: Boolean = false) {
        sessionStorage.updateAccountId(accountId)
        sessionStorage.setPageTechnology(tech)
        sessionStorage.setCdpEnabled(enableCdp)

        if (enableCdp) {
            CdpTracker.registerOnIdentityResolved(
                userVars = { storage.readUserVars() },
                timezone = TimeZone.getDefault().id,
                legacySegments = { storage.readUserSegments() },
                writeLegacySegments = { storage.setUserSegment(it) }
            )
        }

        configureSession()
        pingEmitter.onResumeCallback = ::configureSession
    }

    private fun configureSession() {
        val session = storage.readSession()
        val startedNewSession: Boolean
        if (session == null) {
            sessionStorage.updateSession()
            startedNewSession = true
        } else {
            val lastPing = storage.readLastPingTimeStamp() ?: 0L
            val lastActivity = maxOf(session.timeStamp, lastPing)
            startedNewSession = lastActivity < thirtyMinsAgoInSeconds()
            if (startedNewSession) {
                sessionStorage.updateSession()
            }
        }

        if (startedNewSession && sessionStorage.readCdpEnabled()) {
            CdpTracker.onSessionStart()
        }
    }

    @Deprecated("Use trackNewPage(url) method", replaceWith = ReplaceWith("trackNewPage(url)"))
    override fun startPageView(url: String) {
        trackNewPage(url)
    }

    override fun trackNewPage(url: String, rs: String?) {
        check(initialized) { compassNotInitializedErrorMessage }

        val page = Page(url)
        sessionStorage.updatePage(page)
        sessionStorage.clearPageVars()
        sessionStorage.clearPageMetrics()
        sessionStorage.updateRecirculationSource(rs)
        pingEmitter.start(url, page.pageId, sessionStorage.readSession().id)
        MultimediaTracking.reset()
        CdpTracker.onNewPage()
    }

    @Deprecated("Use trackNewPage(url, scrollView) method", replaceWith = ReplaceWith("trackNewPage(url, scrollView)"))
    override fun<T> startPageView(url: String, scrollView: T) where T: FrameLayout, T: ScrollingView {
        trackNewPage(url, scrollView)
    }

    @Deprecated("Use trackNewPage(url, scrollView) method", replaceWith = ReplaceWith("trackNewPage(url, scrollView)"))
    override fun startPageView(url: String, scrollView: ScrollView) {
        trackNewPage(url, scrollView)
    }

    @Deprecated("Use trackNewPage(url, scrollView) method", replaceWith = ReplaceWith("trackNewPage(url, scrollView)"))
    override fun startPageView(url: String, scrollView: RecyclerView) {
        trackNewPage(url, scrollView)
    }

    override fun<T> trackNewPage(url: String, scrollView: T, rs: String?) where T: FrameLayout, T: ScrollingView {
        trackFrameLayoutPageView(url, scrollView, rs)
    }

    override fun trackNewPage(url: String, scrollView: ScrollView, rs: String?) {
        trackFrameLayoutPageView(url, scrollView, rs)
    }

    private fun<T> trackFrameLayoutPageView(url: String, scrollView: T, rs: String? = null) where T: FrameLayout {
        trackNewPage(url, scrollView, fun(view: T, scroll: Int, _: Int): Double {
            val scrollViewHeight = (view.getChildAt(0).bottom - scrollView.height).toDouble()

            return scroll.toDouble() / scrollViewHeight * 100
        }, rs)
    }

    override fun trackNewPage(url: String, scrollView: RecyclerView, rs: String?) {
        var currentScroll = 0

        trackNewPage(url, scrollView, fun(view: RecyclerView, scroll: Int, oldScroll: Int): Double {
                val scrollViewHeight =
                    (view.computeVerticalScrollRange() - view.computeVerticalScrollExtent()).toDouble()
                val dScroll = scroll - oldScroll
                currentScroll += dScroll

                return currentScroll / scrollViewHeight * 100
            }, rs
        )
    }

    private fun<T> trackNewPage(
        url: String,
        scrollView: T,
        scrollMeasurer: (view: T, scrollY: Int, oldScrollY: Int) -> Double,
        rs: String? = null)
    where T: ViewGroup {
        check(initialized) { compassNotInitializedErrorMessage }
        scrollView.setOnScrollChangeListener { view, _, scrollY, _, oldScrollY ->
            view?.let {
                @Suppress("UNCHECKED_CAST")
                val scrollPosition =
                    scrollMeasurer(view as T, scrollY, oldScrollY).toScrollPercentage()

                pingEmitter.updateScrollPercentage(scrollPosition)
            }
        }

        trackNewPage(url, rs)
    }

    private fun screenUrl(screen: String): String {
        return "https://marfeelwhois.mrf.io/dynamic/${sessionStorage.readAccountId()}/${Uri.encode(screen)}"
    }

    override fun trackScreen(screen: String, rs: String?) {
        trackNewPage(screenUrl(screen), rs)
    }

    override fun<T> trackScreen(screen: String, scrollView: T, rs: String?) where T: FrameLayout, T: ScrollingView {
        trackNewPage(screenUrl(screen), scrollView, rs)
    }

    override fun trackScreen(screen: String, scrollView: ScrollView, rs: String?) {
        trackNewPage(screenUrl(screen), scrollView, rs)
    }

    override fun trackScreen(screen: String, scrollView: RecyclerView, rs: String?) {
        trackNewPage(screenUrl(screen), scrollView, rs)
    }

    internal fun Double.toScrollPercentage(): Int {
        val range = 0..100
        return when {
            this > range.last -> range.last
            else -> this.toInt()
        }
    }

    override fun stopTracking() {
        check(initialized) { compassNotInitializedErrorMessage }
        pingEmitter.stop()
    }

    @Deprecated("Use setSiteUserId(userID) method", replaceWith = ReplaceWith("setSiteUserId(userId)"))
    override fun setUserId(userId: String) {
        setSiteUserId(userId)
    }

    override fun setSiteUserId(userId: String) {
        check(initialized) { compassNotInitializedErrorMessage }
        storage.updateUserId(userId)
        CdpTracker.onSiteUserId(userId)
    }

    override fun setUserType(userType: UserType) {
        check(initialized) { compassNotInitializedErrorMessage }
        storage.updateUserType(userType)
    }

    override fun updateScrollPercentage(scrollPosition: Int) {
        check(initialized) { compassNotInitializedErrorMessage }
        pingEmitter.updateScrollPercentage(scrollPosition)
    }

    override fun getRFV(): String? =
        getRFV.invoke()?.toString()

    override fun getRFV(onResult: (String?) -> Unit) {
        check(initialized) { compassNotInitializedErrorMessage }
        coroutineScope.launch {
            val response = getRFV()
            onResult(response)
        }
    }

    override fun trackConversion(conversion: String) {
        check(initialized) { compassNotInitializedErrorMessage }
        sessionStorage.addPendingConversion(conversion)
    }

    override fun trackConversion(conversion: String, options: ConversionOptions) {
        check(initialized) { compassNotInitializedErrorMessage }
        sessionStorage.addPendingConversion(conversion, options)
    }

    override fun setPageVar(name: String, value: String) {
        check(initialized) { compassNotInitializedErrorMessage }

        sessionStorage.addPageVar(name, value)
    }

    override fun setPageMetric(name: String, value: Int) {
        check(initialized) { compassNotInitializedErrorMessage }

        sessionStorage.addPageMetric(name, value)
    }

    override fun setSessionVar(name: String, value: String) {
        check(initialized) { compassNotInitializedErrorMessage }

        sessionStorage.addSessionVar(name, value)
    }

    override fun setUserVar(name: String, value: String) {
        check(initialized) { compassNotInitializedErrorMessage }

        writeUserVar(name, value)
    }

    /**
     * The one write path for device-owned user vars: persists, then pushes the owned
     * set to the CDP profile (debounced). A null [value] removes the var.
     */
    private fun writeUserVar(name: String, value: String?) {
        if (value == null) storage.removeUserVar(name) else storage.setUserVar(name, value)
        if (sessionStorage.readCdpEnabled()) CdpTracker.flushUserVars { storage.readUserVars() }
    }

    override fun addUserSegment(name: String) {
        storage.setUserSegment(name)
        if (sessionStorage.readCdpEnabled()) CdpTracker.addCdpSegment(name)
    }

    /**
     * Bulk replace is the one shape where intent is ambiguous — an echo of
     * [getUserSegments] and a deliberate assertion look the same — so a requested key
     * that only the server asserts is dropped (with a warning) instead of becoming
     * device-owned. [addUserSegment] is the unambiguous way to claim ownership.
     */
    override fun setUserSegments(segments: List<String>) {
        val cdpEnabled = sessionStorage.readCdpEnabled()
        val next = if (cdpEnabled) {
            SegmentOwnership.rejectUnownedSegments(
                requested = segments,
                owned = storage.readUserSegments(),
                server = CdpTracker.listServerSegments()
            )
        } else {
            segments
        }
        storage.setUserSegment(next)
        if (cdpEnabled) CdpTracker.setCdpSegments(next)
    }

    override fun getUserSegments(): List<String> = userData.segments()

    override suspend fun getUserSegmentsAsync(): List<String> = userData.segmentsAsync()

    override fun getUserVars(): Map<String, String> = userData.vars()

    override suspend fun getUserVarsAsync(): Map<String, String> = userData.varsAsync()

    override suspend fun resetUser() {
        userResetter.reset()
    }

    override fun resetUser(onComplete: () -> Unit) {
        val run = userResetter.start()
        coroutineScope.launch {
            try {
                run.await()
            } catch (_: Exception) {
            }
            onComplete()
        }
    }

    @Deprecated("Use resetUser()", ReplaceWith("resetUser()"))
    override suspend fun resetIdentity() {
        resetUser()
    }

    override fun removeUserSegment(name: String) {
        storage.removeUserSegment(name)
        if (sessionStorage.readCdpEnabled()) CdpTracker.removeCdpSegment(name)
    }

    override fun clearUserSegments() {
        storage.clearUserSegments()
        if (sessionStorage.readCdpEnabled()) CdpTracker.clearCdpSegments()
    }

    override fun setUserConsent(hasConsent: Boolean) {
        storage.updateUserConsent(hasConsent)
        CdpTracker.onConsentChanged()
    }

    override fun getUserId(): String {
        return storage.readOriginalUserId()
    }

    override fun getSessionId(): String {
        return sessionStorage.readSession().id
    }

    override fun setLandingPage(landingPage: String) {
        sessionStorage.setLandingPage(landingPage)
    }
}
